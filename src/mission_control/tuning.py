"""Loading the tuned gains that ``scripts/tune_gains.py`` produces.

``config/tuned_gains.yaml`` is a committed artifact, regenerated by the tuning
script and consumed here. The indirection exists so that a number in the README
can be traced back to the exact gains that produced it, without those gains
being buried in a dataclass default that somebody edits later.

If the file is missing, the dataclass defaults are used and a note is available
through :func:`tuning_source`. The repository is expected to ship the file; the
fallback is so that a fresh checkout with a deleted ``config/`` still runs
rather than failing at import time.
"""

from __future__ import annotations

import os

import numpy as np

CONFIG_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
    "config",
    "tuned_gains.yaml",
)

_CACHE = {}


def load_tuned(path: str = None) -> dict:
    """Read the tuned-gains file. Returns an empty dict if it is absent."""
    path = path or CONFIG_PATH
    if path in _CACHE:
        return _CACHE[path]

    data = {}
    if os.path.exists(path):
        try:
            import yaml

            with open(path, "r", encoding="utf-8") as handle:
                data = yaml.safe_load(handle) or {}
        except ImportError:
            data = {}
    _CACHE[path] = data
    return data


def tuning_source(path: str = None) -> str:
    """Where the gains in force came from. Recorded in the results."""
    path = path or CONFIG_PATH
    return path if load_tuned(path) else "dataclass defaults (config/tuned_gains.yaml absent)"


def pid_gains(path: str = None):
    """Tuned :class:`~mission_control.control.pid_tracker.PidGains`."""
    from .control.pid_tracker import PidGains

    gains = PidGains()
    tuned = load_tuned(path).get("pid") or {}
    for key in ("position_p", "velocity_p", "velocity_i", "velocity_d"):
        if key in tuned:
            setattr(gains, key, np.asarray(tuned[key], dtype=float))
    return gains


def mpc_weights(path: str = None):
    """Tuned :class:`~mission_control.control.mpc_tracker.MpcWeights`."""
    from .control.mpc_tracker import MpcWeights

    tuned = load_tuned(path).get("mpc") or {}
    weights = MpcWeights(
        horizon=int(tuned.get("horizon", MpcWeights.horizon)),
        step_s=float(tuned.get("step_s", MpcWeights.step_s)),
        lag_tau_s=float(tuned.get("lag_tau_s", MpcWeights.lag_tau_s)),
    )
    for key in ("position_weight", "velocity_weight", "acceleration_weight",
                "input_weight", "input_rate_weight"):
        if key in tuned:
            setattr(weights, key, np.asarray(tuned[key], dtype=float))
    for key in ("terminal_scale", "disturbance_gain", "disturbance_limit",
                "max_acceleration_xy", "max_acceleration_up", "max_acceleration_down"):
        if key in tuned:
            setattr(weights, key, float(tuned[key]))
    return weights
